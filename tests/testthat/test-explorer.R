explorer_test_config <- function(...) repl_config(color = FALSE, settings_file = NULL, ...)
explorer_test_event <- function(key = "", text = "", type = if (nzchar(text)) "text" else "key",
                                modifiers = character(), ...) {
  c(list(type = type, key = key, text = text, modifiers = modifiers), list(...))
}

test_that("nested lists and data frame columns support child and parent navigation", {
  cfg <- explorer_test_config()
  value <- list(table = utils::head(iris, 3L), nested = list(values = 1:5))
  before <- serialize(value, NULL)
  state <- .explorer_state(value, "result")
  state <- .explorer_apply(state, explorer_test_event("enter"), cfg)
  expect_length(state$stack, 2L)
  expect_identical(state$stack[[2L]]$label, "table")
  expect_identical(state$stack[[2L]]$meta$shape, "3 x 5")
  state <- .explorer_apply(state, explorer_test_event("right"), cfg)
  expect_length(state$stack, 3L)
  expect_identical(state$stack[[3L]]$label, "Sepal.Length")
  expect_equal(state$stack[[3L]]$value, iris$Sepal.Length[1:3])
  expect_identical(state$stack[[3L]]$view, "preview")
  preview <- .explorer_content(state$stack[[3L]], 100L)$lines
  expect_true(all(vapply(c("5.1", "4.9", "4.7"), function(value)
    any(grepl(value, preview, fixed = TRUE)), logical(1L))))
  state <- Reduce(function(current, key) .explorer_apply(current, explorer_test_event(key), cfg),
    c("enter", "right", "enter", "right"), init = state)
  expect_identical(vapply(state$stack, `[[`, character(1L), "label"), c("result", "table", "Sepal.Length"))
  expect_identical(.explorer_content(state$stack[[3L]], 100L)$lines, preview)
  state <- .explorer_apply(state, explorer_test_event("backspace"), cfg)
  expect_length(state$stack, 2L)
  state <- .explorer_apply(state, explorer_test_event("left"), cfg)
  expect_length(state$stack, 1L)
  expect_identical(serialize(value, NULL), before)
})

test_that("environment browsing never forces deferred or active bindings", {
  cfg <- explorer_test_config()
  env <- new.env(parent = emptyenv())
  calls <- 0L
  makeActiveBinding("active", function(value) { calls <<- calls + 1L; stop("executed active binding") }, env)
  delayedAssign("deferred", { calls <<- calls + 1L; stop("forced promise") }, assign.env = env)
  env$ordinary <- list(value = 42L)
  state <- .explorer_state(env, "Workspace", limit = 2L)
  loaded <- .explorer_load(state$stack[[1L]])
  expect_identical(loaded$data$name, c("active", "deferred"))
  expect_true(all(grepl("not evaluated", loaded$data$preview, fixed = TRUE)))
  blocked <- .explorer_apply(state, explorer_test_event("enter"), cfg)
  expect_length(blocked$stack, 1L)
  expect_match(blocked$status, "Cannot open")
  blocked <- .explorer_apply(blocked, explorer_test_event("down"), cfg)
  blocked <- .explorer_apply(blocked, explorer_test_event("enter"), cfg)
  expect_length(blocked$stack, 1L)
  expect_identical(calls, 0L)
  state <- .explorer_apply(state, explorer_test_event(text = "]"), cfg)
  expect_identical(.explorer_load(state$stack[[1L]])$data$name, "ordinary")
  opened <- .explorer_apply(state, explorer_test_event("enter"), cfg)
  expect_length(opened$stack, 2L)
  expect_identical(calls, 0L)
})

test_that("custom object methods are not called by structure or preview", {
  class_name <- "prismrepl_explorer_test_danger"
  method_names <- paste0(c("print", "format", "[", "[[", "length", "dim", "names", "str"), ".", class_name)
  expect_false(any(vapply(method_names, exists, logical(1L), envir = .GlobalEnv, inherits = FALSE)))
  invisible(lapply(method_names, assign, value = function(...) stop("custom method executed"), envir = .GlobalEnv))
  withr::defer(rm(list = method_names, envir = .GlobalEnv))
  value <- structure(list(a = 1:3, b = pi), class = class_name)
  state <- .explorer_state(value)
  expect_identical(.explorer_load(state$stack[[1L]])$data$name, c("a", "b"))
  expect_true(is.character(.explorer_preview(value, 80L, 10L)))
  scalar <- structure(c(pi, 1/3), class = class_name)
  expect_identical(.explorer_brief(scalar), "3.14159, 0.333333")
})

test_that("factor and ordinary Date displays preserve their meaningful values", {
