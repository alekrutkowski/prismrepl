test_that("new defaults are independent and persistent values take precedence", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  cfg <- repl_config(settings_file = path)
  expect_true(cfg$rainbow)
  expect_true(cfg$autopair)
  expect_identical(cfg$ai_provider, "mistral")
  expect_null(cfg$ai_url)
  expect_false(file.exists(path))
  repl_settings(rainbow = FALSE, autopair = FALSE, ai_provider = "claude", file = path)
  saved <- repl_config(settings_file = path)
  expect_false(saved$rainbow)
  expect_false(saved$autopair)
  expect_identical(saved$ai_provider, "claude")
  expect_true(repl_config(rainbow = TRUE, settings_file = path)$rainbow)
  expect_false(repl_config(rainbow = TRUE, settings_file = path)$autopair)
  expect_identical(repl_config(ai_provider = "chatgpt", settings_file = path)$ai_provider, "chatgpt")
  expect_error(repl_settings(rainbow = NA, file = path), "rainbow")
  expect_error(repl_config(autopair = "on", settings_file = NULL), "autopair")
})

test_that("first-run appearance is detected without writes and saved only by session startup", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  calls <- logical()
  local_mocked_bindings(.initial_theme = function(refresh = FALSE) {
    calls <<- c(calls, refresh)
    "paper"
  })
  cfg <- repl_config(settings_file = path)
  expect_identical(cfg$theme$name, "paper")
  expect_identical(calls, FALSE)
  expect_true(cfg$theme_initial)
  expect_false(file.exists(path))
  temporary <- cfg
  temporary$persist <- FALSE
  expect_false(.remember_initial_theme(temporary))
  expect_false(file.exists(path))
  expect_true(.remember_initial_theme(cfg))
  expect_identical(repl_settings(file = path)$theme, "paper")
  repl_settings(theme = "black", file = path)
  expect_false(.remember_initial_theme(cfg))
  expect_identical(repl_settings(file = path)$theme, "black")
  expect_identical(repl_config(settings_file = path)$theme$name, "black")
  expect_identical(repl_config(theme = "white", settings_file = path)$theme$name, "white")
  expect_identical(calls, FALSE)
  expect_identical(repl_config(theme = "auto", settings_file = path)$theme$name, "paper")
  expect_identical(calls, c(FALSE, TRUE))
  state <- new.env(parent = emptyenv())
  state$config <- repl_config(color = FALSE, settings_file = path)
  capture.output(.repl_command(":theme auto", state, new.env()))
  expect_identical(utils::tail(calls, 1L), TRUE)
  expect_identical(repl_settings(file = path)$theme, "paper")
})

test_that("custom AI templates survive switching providers and validate before saving", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  url <- "https://example.com/chat?q={prompt}&mode=code"
  repl_settings(ai_provider = "custom", ai_url = url, file = path)
  expect_identical(repl_config(settings_file = path)$ai_url, url)
  expect_identical(repl_config(settings_file = path)$ai_provider, "custom")
  repl_settings(ai_provider = "mistral", file = path)
  expect_identical(repl_settings(file = path)$ai_url, url)
  expect_error(repl_settings(ai_provider = "unavailable", file = path))
  expect_identical(repl_settings(file = path)$ai_provider, "mistral")
  expect_error(repl_settings(ai_url = "https://example.com/", file = path))
  expect_identical(repl_settings(file = path)$ai_url, url)
  writeLines(c("Version: 1", "Rainbow: perhaps"), path)
  expect_error(repl_settings(file = path), "logical preference")
  writeLines(c("Version: 1", "AI-Provider: custom"), path)
  expect_error(repl_settings(file = path), "custom")
})

test_that("editing and AI commands save preferences, complete names and invalidate painting", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  state <- new.env(parent = emptyenv())
  state$config <- repl_config(color = FALSE, settings_file = path)
  state$config$screen <- screen_state()
  env <- new.env()
  command <- function(text) capture.output(.repl_command(text, state, env))
  command(":ra off")
  command(":au off")
  command(":ai chatgpt")
  expect_false(repl_config(settings_file = path)$rainbow)
  expect_false(repl_config(settings_file = path)$autopair)
  expect_identical(repl_config(settings_file = path)$ai_provider, "chatgpt")
  state$config$screen$last_frame <- list(lines = "old painting")
  command(":rainbow toggle")
  expect_true(state$config$rainbow)
  expect_null(state$config$screen$last_frame)
  state$config$persist <- FALSE
  command(":autopair on")
  expect_true(state$config$autopair)
  expect_false(repl_config(settings_file = path)$autopair)
  expect_error(command(":rainbow perhaps"), "on, off or toggle")
  expect_error(command(":ai mistral https://example.com/?q={prompt}"), "only after")
  expect_identical(.command_parse(":ra off")$command, "rainbow")
  expect_identical(.command_parse(":au on")$command, "autopair")
  expect_true("claude" %in% complete_r(":ai cl", envir = env)$candidates)
  expect_identical(complete_r(":rainbow tog", envir = env)$candidates, "toggle")
  expect_identical(complete_r(":autopair of", envir = env)$candidates, "off")
})

test_that("reset restores all editing and provider defaults without retaining a custom URL", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  repl_settings(theme = "white", rainbow = FALSE, autopair = FALSE, ai_provider = "custom",
    ai_url = "https://example.com/?q={prompt}", file = path)
  state <- new.env(parent = emptyenv())
  state$config <- repl_config(color = FALSE, settings_file = path)
  capture.output(.repl_command(":settings reset", state, new.env()))
  fresh <- repl_config(settings_file = path)
  expect_true(fresh$rainbow)
  expect_true(fresh$autopair)
  expect_identical(fresh$ai_provider, "mistral")
  expect_null(fresh$ai_url)
  expect_null(state$config$ai_url)
  expect_identical(fresh$theme$name, .initial_theme())
})

test_that("explain uses the selected provider and copies only on explicit request", {
  state <- new.env(parent = emptyenv())
  state$config <- repl_config(color = FALSE, settings_file = NULL, ai_provider = "gemini")
  state$last_error <- list(error = simpleError("test error"), code = "secret_code()", trace = "private_call()")
  copied <- NULL
  local_mocked_bindings(.clipboard_write = function(text) {
    copied <<- text
    list(ok = TRUE, reason = "Copied selection to the test clipboard.", backend = "test")
  })
  output <- capture.output(.repl_command(":explain", state, new.env()))
  expect_null(copied)
  expect_true(any(grepl("gemini.google.com", output, fixed = TRUE)))
  expect_true(any(grepl(":explain copy", output, fixed = TRUE)))
  capture.output(.repl_command(":explain copy minimal", state, new.env()))
  expect_match(copied, "test error", fixed = TRUE)
  expect_false(grepl("secret_code", copied, fixed = TRUE))
  expect_false(grepl("private_call", copied, fixed = TRUE))
  capture.output(.repl_command(":explain copy", state, new.env()))
  expect_match(copied, "secret_code()", fixed = TRUE)
  expect_error(.repl_command(":explain copy copy", state, new.env()), "use :explain")
})

test_that("sidebar modules pin shared colored hints below their own content", {
  env <- list2env(stats::setNames(as.list(seq_len(30L)), paste0("variable", seq_len(30L))))
  cfg <- repl_config(color = TRUE, color_depth = 16777216L, settings_file = NULL)
  groups <- .session_sidebar(env, cfg)
  expect_named(attr(groups$WORKSPACE, "hints"), c(":objects", ":rm"))
  expect_named(attr(groups$PACKAGES, "hints"), c(":packages", ":detach"))
  expect_named(attr(groups$FILES, "hints"), ":files")
  lapply(c(12L, 28L, 50L), function(height) {
    frame <- .sidebar_frame(groups, 35L, height, cfg)
    plain <- cli::ansi_strip(frame$lines)
    lapply(names(groups), function(name) {
      hints <- attr(groups[[name]], "hints")
      row <- which(startsWith(trimws(plain), paste(names(hints)[[1L]], hints[[1L]])))
      expect_length(row, 1L)
      expect_identical(cli::ansi_strip(frame$lines[[row]]),
        paste0("  ", cli::ansi_strip(.footer_hints(hints, cfg, 33L))))
      expect_true(startsWith(frame$lines[[row]], paste0("\033[", cfg$theme$colors[["status"]], "m")))
      expect_true(startsWith(frame$actions[[row]], ":"))
    })
    expect_true(all(vapply(frame$lines, .screen_width, numeric(1L)) <= 35L))
  })
})
