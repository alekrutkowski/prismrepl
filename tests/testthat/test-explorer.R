  expect_equal(nrow(.explorer_load(unnamed$stack[[1L]])$data), 1L)
})

test_that("large child collections use bounded batches and bounded metadata caches", {
  cfg <- explorer_test_config()
  state <- .explorer_state(as.list(seq_len(101L)), limit = 10L)
  first <- .explorer_load(state$stack[[1L]])
  expect_equal(first$indices, 1:10)
  state <- .explorer_apply(state, explorer_test_event(text = "]"), cfg)
  expect_equal(.explorer_load(state$stack[[1L]])$indices, 11:20)
  state <- .explorer_apply(state, explorer_test_event("end"), cfg)
  expect_equal(.explorer_load(state$stack[[1L]])$indices, 101L)
  state <- .explorer_apply(state, explorer_test_event("home"), cfg)
  expect_equal(.explorer_load(state$stack[[1L]])$indices, 1:10)
  for (i in seq_len(8L)) {
    state <- .explorer_apply(state, explorer_test_event(text = "]"), cfg)
    .explorer_load(state$stack[[1L]])
  }
  expect_lte(length(ls(state$stack[[1L]]$cache$summaries)), 40L)
})

