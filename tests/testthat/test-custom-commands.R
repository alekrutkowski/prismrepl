local_custom_cache <- function() {
  cache <- .custom_command_state
  saved <- as.list(cache, all.names = TRUE)
  withr::defer({
    rm(list = ls(cache, all.names = TRUE), envir = cache)
    invisible(list2env(saved, envir = cache))
  }, envir = parent.frame())
  rm(list = ls(cache, all.names = TRUE), envir = cache)
  invisible(NULL)
}

custom_test_function <- function(expression) eval(substitute(expression), baseenv())

test_that("custom registry paths respect explicit isolation without creating files", {
  directory <- withr::local_tempdir()
  preferences <- file.path(directory, "not-created", "preferences.dcf")
  withr::local_envvar(PRISMREPL_COMMANDS_FILE = "")
  expect_identical(repl_commands_file(preferences), file.path(dirname(preferences), "commands.rds"))
  expect_false(dir.exists(dirname(preferences)))
  override <- file.path(directory, "override.rds")
  withr::local_envvar(PRISMREPL_COMMANDS_FILE = override)
  expect_identical(repl_commands_file(preferences), override)
  expect_null(repl_commands_file(NULL))
  expect_false(file.exists(override))
  expect_error(repl_commands_file(""), "settings_file")
})

test_that("registration stores metadata and retains the live function object", {
  local_custom_cache()
  directory <- withr::local_tempdir("custom command files ")
  path <- file.path(directory, "new directory", "commands.rds")
  fun <- custom_test_function(function(first, second = "default", ..., last = "last")
    list(first, second, ..., last = last))
  answer <- withVisible(repl_add_command(":Custom-One", fun,
    description = "Read Unicode text", alias = ":ZZ", file = path, external = TRUE))
  expect_false(answer$visible)
  expect_identical(answer$value$name, "custom-one")
  expect_identical(answer$value$alias, "zz")
  expect_true(answer$value$persistent)
  expect_true(answer$value$external)
  expect_true(file.exists(path))
  entry <- .custom_command_lookup("ZZ", path, load = TRUE)
  expect_identical(entry$fun, fun)
  expect_identical(entry$parameters, c("first", "second", "...", "last"))
  expect_identical(entry$required, c(TRUE, FALSE, FALSE, FALSE))
  expect_type(entry$function_raw, "raw")
  expect_identical(repl_custom_commands(path), answer$value)
  manifest <- readRDS(path)
  expect_identical(manifest$version, 1L)
  expect_identical(names(manifest$commands), "custom-one")
  expect_false("fun" %in% names(manifest$commands[[1L]]))
  expect_type(manifest$commands[[1L]]$function_raw, "raw")
  catalog <- .custom_command_catalog(path)
  expect_identical(catalog$group, "Custom")
  expect_identical(catalog$insert, ":custom-one ")
  expect_identical(catalog$command, ":custom-one FIRST [SECOND] [ARG ...] [LAST]")
})

test_that("zero-argument and session-only commands need no file", {
  local_custom_cache()
  fun <- custom_test_function(function() "ready")
  repl_add_command("customzero", fun, file = NULL)
  metadata <- repl_custom_commands(NULL)
  expect_identical(metadata$name, "customzero")
  expect_false(metadata$persistent)
  expect_identical(metadata$usage, ":customzero")
  expect_identical(.custom_command_catalog(NULL)$insert, ":customzero")
  expect_identical(.custom_command_lookup("customzero", NULL, TRUE)$fun(), "ready")
  expect_length(.custom_command_lookup("customzero", NULL)$parameters, 0L)
  removed <- withVisible(repl_remove_command(":CUSTOMZERO", NULL))
  expect_false(removed$visible)
  expect_identical(removed$value, "customzero")
  expect_equal(nrow(repl_custom_commands(NULL)), 0L)
  expect_null(.custom_command_lookup("customzero", NULL))
})

test_that("custom command names and aliases cannot hide existing commands", {
  local_custom_cache()
  path <- withr::local_tempfile(fileext = ".rds")
  fun <- custom_test_function(function(x) x)
  expect_error(repl_add_command("help", fun, file = path), "built-in")
  expect_error(repl_add_command(":H", fun, file = path), "built-in")
  expect_error(repl_add_command("customone", fun, alias = "a", file = path), "built-in")
  expect_false(file.exists(path))
  repl_add_command("customone", fun, alias = "zz", file = path)
  expect_error(repl_add_command("customone", fun, file = path), "replace = TRUE", fixed = TRUE)
  expect_error(repl_add_command("zz", fun, file = path), "collide")
  expect_error(repl_add_command("customtwo", fun, alias = "zz", file = path), "collide")
  expect_error(repl_add_command("customtwo", fun, alias = "customone", file = path), "collide")
  replacement <- custom_test_function(function() "changed")
  repl_add_command("customone", replacement, alias = "zy", file = path, replace = TRUE)
  expect_null(.custom_command_lookup("zz", path))
  expect_identical(.custom_command_lookup("zy", path, TRUE)$fun(), "changed")
  expect_identical(repl_remove_command("zy", path), "customone")
  expect_equal(nrow(repl_custom_commands(path)), 0L)
  expect_error(repl_remove_command("help", path), "cannot be removed")
})

test_that("registry validation rejects ambiguous identifiers and invalid functions", {
  local_custom_cache()
  path <- withr::local_tempfile()
  fun <- custom_test_function(function(x) x)
  invisible(lapply(c("", "two words", "1name", "two::names", "x.y", "a;stop(1)"),
    function(name) expect_error(repl_add_command(name, fun, file = path), "command name")))
  expect_error(repl_add_command("customone", base::sum, file = path), "ordinary R function")
  expect_error(repl_add_command("customone", NULL, file = path), "ordinary R function")
  expect_error(repl_add_command("customone", fun, alias = "customone", file = path), "differ")
  expect_error(repl_add_command("customone", fun, alias = c("zz", "zy"), file = path), "scalar")
  expect_error(repl_add_command("customone", fun, description = "two\nlines", file = path), "one line")
  expect_error(repl_add_command("customone", fun, description = NA_character_, file = path), "non-missing")
  expect_error(repl_add_command("customone", fun, external = NA, file = path), "logical")
  expect_false(file.exists(path))
})

test_that("metadata access never restores or invokes user function bodies", {
  local_custom_cache()
  path <- withr::local_tempfile()
  fun <- custom_test_function(function() stop("body called"))
  repl_add_command("customlazy", fun, file = path)
  rm(list = .custom_command_key(path), envir = .custom_command_state)
  local_mocked_bindings(unserialize = function(...) stop("unexpected restore"), .package = "base")
  expect_no_error(repl_custom_commands(path))
  expect_no_error(.custom_command_catalog(path))
  expect_no_error(.custom_command_lookup("customlazy", path))
  expect_error(.custom_command_lookup("customlazy", path, TRUE), "unexpected restore")
})

test_that("restoration warnings prevent a function with a substituted environment from running", {
  local_custom_cache()
  path <- withr::local_tempfile()
  repl_add_command("customwarning", custom_test_function(function() "original"), file = path)
  rm(list = .custom_command_key(path), envir = .custom_command_state)
  local_mocked_bindings(unserialize = function(...) {
    warning("namespace unavailable; substituting the global environment")
    custom_test_function(function() stop("must not run"))
  }, .package = "base")
  expect_error(.custom_command_lookup("customwarning", path, TRUE), "Could not restore custom command")
  expect_length(.custom_command_state[[.custom_command_key(path)]]$functions, 0L)
  expect_identical(repl_custom_commands(path)$name, "customwarning")
})

test_that("saved local captures and global references keep their R semantics", {
  local_custom_cache()
  path <- withr::local_tempfile()
  captured <- new.env(parent = baseenv())
  captured$prefix <- "donn\u00e9es \u5206\u6790"
  fun <- eval(quote(function(x) paste(prefix, x)), captured)
  repl_add_command("customcapture", fun, file = path)
  rm(list = .custom_command_key(path), envir = .custom_command_state)
  restored <- .custom_command_lookup("customcapture", path, TRUE)$fun
  expect_false(identical(environment(restored), captured))
  expect_identical(restored("text"), "donn\u00e9es \u5206\u6790 text")
  global_fun <- eval(quote(function(x) x), globalenv())
  repl_add_command("customglobal", global_fun, file = path)
  rm(list = .custom_command_key(path), envir = .custom_command_state)
  expect_identical(environment(.custom_command_lookup("customglobal", path, TRUE)$fun), globalenv())
})

test_that("unrelated registry changes preserve a function's live captured state", {
  local_custom_cache()
  path <- withr::local_tempfile()
  captured <- new.env(parent = baseenv())
  captured$count <- 0L
  fun <- eval(quote(function() { count <<- count + 1L; count }), captured)
  repl_add_command("customcounter", fun, file = path)
  expect_identical(.custom_command_lookup("customcounter", path, TRUE)$fun(), 1L)
  repl_add_command("customother", custom_test_function(function(x) x), file = path)
  expect_identical(.custom_command_lookup("customcounter", path, TRUE)$fun, fun)
  expect_identical(.custom_command_lookup("customcounter", path, TRUE)$fun(), 2L)
  expect_no_error(repl_custom_commands(path))
  expect_identical(.custom_command_lookup("customcounter", path, TRUE)$fun(), 3L)
})

test_that("a broken saved function leaves other commands and metadata usable", {
  local_custom_cache()
  path <- withr::local_tempfile()
  repl_add_command("custombad", custom_test_function(function() "bad"), file = path)
  repl_add_command("customgood", custom_test_function(function() "good"), file = path)
  manifest <- readRDS(path)
  manifest$commands$custombad$function_raw <- as.raw(c(1L, 2L, 3L))
  saveRDS(manifest, path, compress = FALSE)
  expect_identical(repl_custom_commands(path)$name, c("custombad", "customgood"))
  expect_error(.custom_command_lookup("custombad", path, TRUE), "Could not restore custom command")
  expect_identical(.custom_command_lookup("customgood", path, TRUE)$fun(), "good")
})

test_that("corrupt registries warn once while strict operations retain the file", {
  local_custom_cache()
  path <- withr::local_tempfile()
  writeLines("not a serialized registry", path)
  before <- readBin(path, "raw", n = file.info(path)$size)
  expect_warning(expect_length(.custom_command_entries(path), 0L), "Using built-in commands only")
  expect_no_warning(.custom_command_catalog(path))
  expect_error(repl_custom_commands(path), "could not be read")
  expect_error(repl_add_command("customone", custom_test_function(function() NULL), file = path),
    "could not be read")
  expect_identical(readBin(path, "raw", n = file.info(path)$size), before)
  writeLines("changed invalid registry contents", path)
  expect_warning(.custom_command_entries(path), "Using built-in commands only")
})

test_that("failed writes and concurrent changes retain the preceding registry", {
  local_custom_cache()
  path <- withr::local_tempfile()
  repl_add_command("customone", custom_test_function(function() "first"), file = path)
  before <- readBin(path, "raw", n = file.info(path)$size)
  local_mocked_bindings(file.rename = function(...) FALSE, .package = "base")
  expect_error(repl_add_command("customtwo", custom_test_function(function() "second"), file = path),
    "previous registry was retained")
  expect_identical(readBin(path, "raw", n = file.info(path)$size), before)
  expect_identical(repl_custom_commands(path)$name, "customone")
  expect_false(dir.exists(paste0(path, ".lock")))
  expect_error(.write_custom_command_entries(.custom_command_entries(path), path, list()),
    "changed while saving")
  expect_identical(readBin(path, "raw", n = file.info(path)$size), before)
})

test_that("a competing writer's lock is retained and cannot lose saved commands", {
  local_custom_cache()
  path <- withr::local_tempfile()
  fun <- custom_test_function(function() "saved")
  repl_add_command("customone", fun, file = path)
  before <- readBin(path, "raw", n = file.info(path)$size)
  lock <- paste0(path, ".lock")
  dir.create(lock)
  withr::defer(unlink(lock, recursive = TRUE))
  expect_error(repl_add_command("customtwo", fun, file = path), "writer lock")
  expect_identical(readBin(path, "raw", n = file.info(path)$size), before)
  expect_true(dir.exists(lock))
  unlink(lock, recursive = TRUE)
  expect_no_error(repl_add_command("customtwo", fun, file = path))
  expect_identical(repl_custom_commands(path)$name, c("customone", "customtwo"))
  expect_false(dir.exists(lock))
})

test_that("registry file size and manifest format are bounded before loading functions", {
  local_custom_cache()
  path <- withr::local_tempfile()
  saveRDS(list(version = 2L, commands = list()), path, compress = FALSE)
  expect_error(repl_custom_commands(path), "version-1 manifest")
  connection <- file(path, "wb")
  tryCatch({
    seek(connection, 16 * 1024^2, origin = "start")
    writeBin(as.raw(0L), connection)
  }, finally = close(connection))
  expect_error(repl_custom_commands(path), "16 MiB")
})

test_that("a persisted closure works in a fresh R process", {
  local_custom_cache()
  path <- withr::local_tempfile(fileext = ".rds")
  captured <- new.env(parent = baseenv())
  captured$prefix <- "restored"
  repl_add_command("customfresh", eval(quote(function(x) paste(prefix, x)), captured), file = path)
  script <- paste0(".libPaths(", paste(deparse(.libPaths()), collapse = ""), ");",
    "library(prismrepl);", "entry <- getFromNamespace('.custom_command_lookup', 'prismrepl')(",
    "'customfresh', ", paste(deparse(path), collapse = ""), ", load = TRUE);",
    "stopifnot(identical(entry$fun('success'), 'restored success'));cat('RESTORE_OK')")
  executable <- file.path(R.home("bin"), if (.Platform$OS.type == "windows") "Rscript.exe" else "Rscript")
  result <- processx::run(executable, c("--vanilla", "-e", script), timeout = 30000L,
                         error_on_status = FALSE)
  expect_identical(result$status, 0L, info = result$stderr)
  expect_match(result$stdout, "RESTORE_OK", fixed = TRUE)
})
