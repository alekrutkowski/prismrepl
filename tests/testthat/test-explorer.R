test_that("explorer headings and data columns share exact terminal cell starts", {
  cfg <- explorer_test_config()
  value <- list("\u754c e\u0301" = 12345L, "longer label" = c(1.1, 2.2), "x" = "quoted value")
  cell_start <- function(line, needle) {
    index <- regexpr(needle, line, fixed = TRUE)[[1L]]
    expect_gt(index, 0L)
    .panel_cells(substr(line, 1L, index - 1L))
  }
  invisible(lapply(c(80L, 100L, 132L), function(width) {
    state <- .explorer_state(value, "objects", sizes = TRUE)
    frame <- .explorer_frame(state, cfg, c(width = width, height = 18L))
    heading <- frame[[4L]]
    first <- frame[[5L]]
    second <- frame[[6L]]
    expect_equal(cell_start(heading, "Name"), cell_start(first, "\u754c"))
    expect_equal(cell_start(heading, "Type / class"), cell_start(first, "integer"))
    expect_equal(cell_start(heading, "Type / class"), cell_start(second, "numeric"))
    expect_equal(cell_start(heading, "Shape / length"), cell_start(first, "length 1"))
    expect_equal(cell_start(heading, "Size"), cell_start(first, "~"))
    expect_equal(cell_start(heading, "Value"), cell_start(first, "12345"))
    expect_true(all(vapply(frame, .screen_width, numeric(1L)) <= width - 1L))
  }))
})
