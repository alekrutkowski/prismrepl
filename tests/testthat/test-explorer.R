test_that("explorer frames fit narrow windows and preserve safe Unicode labels", {
  cfg <- explorer_test_config()
  value <- list("caf\u00e9" = list("e\u0301" = "\u754c"), "line\nname" = structure(1, class = "bad\033[2J"))
  state <- .explorer_state(value, "Root")
  invisible(lapply(list(c(width = 132L, height = 40L), c(width = 68L, height = 20L),
                       c(width = 25L, height = 8L), c(width = 4L, height = 3L)), function(size) {
    frame <- .explorer_frame(state, cfg, size)
    expect_length(frame, size[["height"]])
    expect_true(all(vapply(frame, .screen_width, numeric(1L)) <= size[["width"]] - 1L))
    expect_false(any(grepl("\033[2J", frame, fixed = TRUE)))
    expect_false(any(grepl("\n", frame, fixed = TRUE)))
  }))
  expect_match(.explorer_load(state$stack[[1L]])$data$name[[2L]], "line\\nname", fixed = TRUE)
  state <- .explorer_apply(state, explorer_test_event("f1"), cfg)
  expect_true(state$help)
  state <- .explorer_apply(state, explorer_test_event(text = "q"), cfg)
  expect_false(state$help)
  expect_false(state$quit)
})

