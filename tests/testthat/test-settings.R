test_that("configuration reads saved choices but explicit arguments win", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  expect_false(file.exists(path))
  cfg <- repl_config(settings_file = path)
  expect_false(file.exists(path))
  repl_settings(theme = "white", pipe = "%>%", mouse = FALSE,
    keybindings = list(newline = "F4", pipe = c("Alt+M", "Ctrl+Shift+M")), file = path)
  saved <- repl_config(settings_file = path)
  expect_identical(saved$theme$name, "white")
  expect_identical(saved$pipe, "%>%")
  expect_false(saved$mouse)
  expect_identical(saved$keybindings$newline, "F4")
  expect_identical(saved$key_lookup[["F4"]], "newline")
  explicit <- repl_config(theme = "black", pipe = "|>", mouse = TRUE,
    keybindings = list(newline = "Ctrl+J"), settings_file = path)
  expect_identical(explicit$theme$name, "black")
  expect_identical(explicit$pipe, "|>")
  expect_true(explicit$mouse)
  expect_identical(explicit$keybindings$newline, "Ctrl+J")
  expect_identical(repl_settings(file = path)$theme, "white")
})

test_that("saved bindings reassign chords and preserve unrelated choices", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  repl_settings(theme = "black", file = path)
  repl_settings(keybindings = list(newline = "ctrl+n"), file = path)
  saved <- repl_settings(file = path)
  expect_identical(saved$theme, "black")
  expect_identical(saved$keybindings$newline, "Ctrl+N")
  expect_identical(saved$keybindings$history_next, character())
  repl_settings(keybindings = list(pipe = "Alt+,"), file = path)
  expect_identical(repl_settings(file = path)$keybindings$pipe, "Alt+,")
  expect_identical(repl_settings(file = path)$keybindings$newline, "Ctrl+N")
  repl_settings(reset = TRUE, file = path)
  expect_identical(repl_settings(file = path), list())
  expect_identical(repl_config(settings_file = path)$keybindings$newline, c("Ctrl+J", "Shift+Enter"))
})

test_that("invalid and oversized preferences are data and safely rejected", {
  local_mocked_bindings(.initial_theme = function(...) "midnight")
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  writeLines(c("Version: 1", "Theme: not-a-theme"), path)
  expect_error(repl_settings(file = path), "unknown saved theme")
  expect_warning(.read_preferences(path, warn = TRUE), "Using defaults")
  expect_identical(repl_config(settings_file = path)$theme$name, "midnight")
  writeLines(c("Version: 1", "Theme: system('never executed')"), path)
  expect_identical(.read_preferences(path), list())
  writeLines(strrep("x", 65537L), path)
  expect_error(repl_settings(file = path), "64 KiB")
  expect_error(repl_keybindings(list(no_such_action = "F4")), "unknown shortcut")
  expect_error(repl_keybindings(list(pipe = "F4", newline = "F4")), "multiple actions")
  expect_error(repl_keybindings(list(pipe = "m")), "Ctrl or Alt")
  expect_error(repl_keybindings(list(pipe = "Super+M")), "modifiers")
  expect_error(repl_keybindings(list(pipe = "Ctrl+F4+")), "separator")
  expect_identical(.normalize_chord("Alt+Plus"), "Alt+Plus")
  expect_identical(.chord_from_parts("+", "alt"), "Alt+Plus")
})

test_that("event matching honors remaps without changing ordinary text", {
  cfg <- repl_config(settings_file = NULL, keybindings = list(newline = "F4"))
  event <- function(key, modifiers = character(), type = "key")
    list(type = type, key = key, modifiers = modifiers)
  expect_identical(.key_action(event("f4"), cfg), "newline")
  expect_identical(.key_action(event("j", "ctrl"), cfg), "")
  expect_identical(.key_action(event("enter", "alt"), cfg), "")
  expect_identical(.key_action(event("m", c("shift", "ctrl")), cfg), "pipe")
  expect_identical(.key_action(event("m", type = "text"), cfg), "")
  expect_identical(.key_action(event("", type = "timeout"), cfg), "")
})

test_that("a failed Windows-style replacement preserves a recovery copy", {
  directory <- tempfile("prism-settings-recovery-")
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE))
  path <- file.path(directory, "preferences.dcf")
  repl_settings(theme = "white", file = path)
  failure <- new.env(parent = environment(.write_preferences))
  failure$file.rename <- function(...) FALSE
  copies <- 0L
  failure$file.copy <- function(...) {
    copies <<- copies + 1L
    if (copies == 1L) base::file.copy(...) else FALSE
  }
  writer <- .write_preferences
  environment(writer) <- failure
  expect_error(writer(list(theme = "black"), path), "recovery copy")
  backups <- list.files(directory, pattern = "backup", full.names = TRUE, all.files = TRUE)
  expect_length(backups, 1L)
  expect_identical(.read_preferences(backups[[1L]])$theme, "white")
})

test_that("console preference commands persist and opt-out stays temporary", {
  path <- tempfile(fileext = ".dcf")
  on.exit(unlink(path))
  state <- new.env(parent = emptyenv())
  state$config <- repl_config(color = FALSE, settings_file = path)
  env <- new.env()
  command <- function(x) capture.output(.repl_command(x, state, env))
  command(":theme white")
  command(":bind newline F4")
  command(":mouse off")
  command(":pipe %>%")
  saved <- repl_config(settings_file = path)
  expect_identical(saved$theme$name, "white")
  expect_identical(saved$keybindings$newline, "F4")
  expect_false(saved$mouse)
  expect_identical(saved$pipe, "%>%")
  command(":unbind pipe")
  expect_identical(repl_config(settings_file = path)$keybindings$pipe, character())
  command(":bind reset")
  expect_identical(repl_config(settings_file = path)$keybindings, repl_keybindings())
  state$config$persist <- FALSE
  command(":theme black")
  expect_identical(state$config$theme$name, "black")
  expect_identical(repl_settings(file = path)$theme, "white")
  state$config <- repl_config(settings_file = NULL, color = FALSE)
  command(":theme black")
  expect_identical(repl_settings(file = path)$theme, "white")
})

