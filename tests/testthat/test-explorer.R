test_that("long atomic previews page without adding child nodes", {
  cfg <- explorer_test_config()
  state <- .explorer_state(seq_len(1000000L), "numbers", limit = 10L)
  first <- .explorer_content(state$stack[[1L]], 80L)$lines
  expect_true(any(grepl("[1]", first, fixed = TRUE)))
  expect_true(any(grepl("[10]", first, fixed = TRUE)))
  state <- .explorer_apply(state, explorer_test_event(text = "]"), cfg)
  expect_identical(state$stack[[1L]]$offset, 10L)
  next_batch <- .explorer_content(state$stack[[1L]], 80L)$lines
  expect_true(any(grepl("[11]", next_batch, fixed = TRUE)))
  expect_true(any(grepl("[20]", next_batch, fixed = TRUE)))
  expect_false(any(grepl("[1]", next_batch, fixed = TRUE)))
  state <- .explorer_apply(state, explorer_test_event("enter"), cfg)
  state <- .explorer_apply(state, explorer_test_event("right"), cfg)
  expect_length(state$stack, 1L)
  expect_identical(state$stack[[1L]]$label, "numbers")
  expect_identical(.explorer_content(state$stack[[1L]], 80L)$lines, next_batch)
  state <- .explorer_apply(state, explorer_test_event(text = "["), cfg)
  expect_identical(state$stack[[1L]]$offset, 0L)
  expect_identical(.explorer_content(state$stack[[1L]], 80L)$lines, first)
  state <- .explorer_apply(state, explorer_test_event("end"), cfg)
  expect_equal(state$stack[[1L]]$offset, 999990L)
  expect_true(any(grepl("[1000000]", .explorer_content(state$stack[[1L]], 80L)$lines, fixed = TRUE)))
  state <- .explorer_apply(state, explorer_test_event("home"), cfg)
  expect_identical(state$stack[[1L]]$offset, 0L)
  expect_identical(.explorer_content(state$stack[[1L]], 80L)$lines, first)
})

